def screening_effort(G: int, P: int) -> tuple[int, int]:
    """Evaluations and tokens of the screening schedule (Eq. generation_cost)."""
    evals = 32 + G * (16 + 8 + 2 + P)
    tokens = 32 * 512 + G * (16 * 512 + 8 * 2048 + (2 + P) * 8192)
    return evals, tokens


def screening_values(pattern: Path, seeds) -> list[float]:
    values = []
    for s in seeds:
        path = Path(str(pattern).format(s=s)) / "run_summary.json"
        values.append(float(json.loads(path.read_text(encoding="utf-8"))["final_metrics"]["wikitext2_ppl"]))
    return values


def table_screening(out):
    ref = {G: screening_values(SCREEN[i][4], (0, 1, 2)) for i, G in ((0, 20), (1, 50))}
    lines = [
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{50mm}rrrrr@{}}", r"\toprule",
        r"Variant & $G$ & Evaluations & Tokens & WikiText-2 & Diff.\ to standard \\", r"\midrule",
        r"\multicolumn{6}{@{}l}{\emph{Mistral-7B, \texttt{q\_proj} scope, $s = 0.25$, $\lambda = 16$}} \\",
    ]
    group = None
    for grp, label, G, P, pattern, seeds in SCREEN:
        if grp != group:
            if group is not None:
                lines.append(r"\addlinespace")
            group = grp
        vals = screening_values(pattern, seeds)
        evals, tokens = screening_effort(G, P)
        ref_vals = [ref[G][s] for s in seeds]
        if grp == "Reference":
            diff = "--"
        else:
            d = st.mean(v - r for v, r in zip(vals, ref_vals))
            diff = signed(d, 2) + ("" if len(seeds) == 3 else f" (seed {seeds[0]})")
        val_txt = (f"{st.mean(vals):.2f} $\\pm$ {st.pstdev(vals):.2f}" if len(vals) == 3 else f"{vals[0]:.2f}")
        evals_txt = f"{evals:,}".replace(",", "{,}")
        lines.append(f"{label} & {G} & {evals_txt} & {tokens / 1e6:.2f}\\,M & {val_txt} & {diff} \\\\")
    # TinyLlama schedule screens (s = 0.125, lambda = 8): reported against the default (max-3) schedule.
    tiny = [
        ("Default ($k_{\\max} = 3$)", "screen_jointaware_tiny_p0_g20_o8"),
        ("Adaptive strength", "screen_adaptive_tiny_pat3_max3_g20_o8"),
        ("Fixed strength, $k_{\\max} = 1$", "screen_fixedstrength_tiny_max1_g20_o8"),
        ("Coarse-to-fine ($3 \\rightarrow 1$)", "screen_coarsetofine_tiny_s3_e1_g20_o8"),
        ("Joint-aware, $p_{\\mathrm{ja}} = 0.25$", "screen_jointaware_tiny_p025_g20_o8"),
    ]
    base = screening_values(RUNS_ROOT / (tiny[0][1] + "_seed{s}"), (0, 1, 2))
    lines += [r"\midrule", r"\multicolumn{6}{@{}l}{\emph{TinyLlama-1.1B, $s = 0.125$, $\lambda = 8$}} \\"]
    for k, (label, prefix) in enumerate(tiny):
        vals = screening_values(RUNS_ROOT / (prefix + "_seed{s}"), (0, 1, 2))
        diff = "--" if k == 0 else signed(st.mean(v - b for v, b in zip(vals, base)), 2)
        lines.append(f"{label} & 20 & & & {st.mean(vals):.2f} $\\pm$ {st.pstdev(vals):.2f} & {diff} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_screening.tex", "\n".join(lines) + "\n")


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    out = Path(args.out)
    L = ledger()
    table_variants(out, L)
    H = horizon_values(L)
    table_horizon(out, H)
    figure_convergence(out, L)
    lx = table_operators(out)
    table_cost(out, L)
    table_screening(out)
    (out / "horizon_values.json").write_text(json.dumps(H, indent=2) + "\n", encoding="utf-8")
    print("wrote", sorted(p.name for p in out.iterdir()))
    print("LX crossover diagnostics:", lx)


if __name__ == "__main__":
    main()
