#!/usr/bin/env python3
"""Generate the LaTeX tables and figure data of thesis Section 6.3 (RQ2).

Inputs (all in this repository): ``thesis_results/fullspace_ledger.csv`` (final
metrics of the full-space runs), the generation logs in
``thesis_results/datalab_raw/`` (convergence, effort, operator diagnostics) and
the run summaries of the screening runs in ``results/runs/`` and
``thesis_results/datalab_raw/cheap_population_crossover/``.

Usage: python scripts/thesis_rq2_tables.py --out <thesis>/generated/rq2
"""

from __future__ import annotations

