def table_variants(out, L):
    lines = [
        r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
        r"& & & & & \multicolumn{2}{c}{Difference to E3} \\", r"\cmidrule(l){6-7}",
        r"Variant & Seed & WikiText-2 & C4 & Calib.\ KL & WikiText-2 & Calib.\ KL \\", r"\midrule",
    ]
    for code in ("E3", "IA", "DW", "P4", "LX"):
        seeds = SEEDS[code]
        for k, seed in enumerate(seeds):
            r = L[f"{code}s{seed}"]
            ref = L[f"E3s{seed}"]
            first = VARIANT_LABEL[code] if k == 0 else ""
            diff = ("--", "--") if code == "E3" else (signed(r["w2"] - ref["w2"]), signed(r["kl"] - ref["kl"], 4))
            lines.append(f"{first} & {seed} & {fmt(r['w2'])} & {fmt(r['c4'])} & {fmt(r['kl'], 4)} & {diff[0]} & {diff[1]} \\\\")
        if len(seeds) == 3:
            vals = [L[f"{code}s{s}"] for s in seeds]
            w2d = [L[f"{code}s{s}"]["w2"] - L[f"E3s{s}"]["w2"] for s in seeds]
            kld = [L[f"{code}s{s}"]["kl"] - L[f"E3s{s}"]["kl"] for s in seeds]
            diff = ("", "") if code == "E3" else (signed(st.mean(w2d)), signed(st.mean(kld), 4))
            lines.append(f"& mean & {ms([v['w2'] for v in vals])} & {ms([v['c4'] for v in vals])} & "
                         f"{ms([v['kl'] for v in vals], 4)} & {diff[0]} & {diff[1]} \\\\")
        lines.append(r"\addlinespace")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    write(out, "tab_variants.tex", "\n".join(lines) + "\n")


def horizon_values(L):
    rows = {}
    for label in [f"{c}s{s}" for c in ("E3", "IA", "DW", "P4", "LX") for s in SEEDS[c]] + ["J12s0", "J12s1", "J12s2"]:
        log = generation_rows(label)
        g21 = log[20]  # held-out diagnostics of generation 21 evaluate the best candidate after 20 generations
        rows[label] = {
            "w2_20": float(g21["wikitext2_ppl"]), "c4_20": float(g21["c4_ppl"]),
            "w2_150": L[label]["w2"], "c4_150": L[label]["c4"],
            "fit_20": float(log[19]["best_search_fitness"]), "fit_150": float(log[149]["best_search_fitness"]),
        }
    return rows


def table_horizon(out, H):
    lines = [
        r"\begin{tabular}{@{}llrrrr@{}}", r"\toprule",
        r"& & \multicolumn{2}{c}{WikiText-2} & \multicolumn{2}{c}{C4} \\",
        r"\cmidrule(lr){3-4}\cmidrule(l){5-6}",
        r"Variant & Seed & $G = 20$ & $G = 150$ & $G = 20$ & $G = 150$ \\", r"\midrule",
    ]
    order = [("E3", SEEDS["E3"]), ("IA", SEEDS["IA"]), ("DW", [0]), ("P4", [0, 1]), ("LX", [0])]
    for code, seeds in order:
        for k, s in enumerate(seeds):
            h = H[f"{code}s{s}"]
            name = code if k == 0 else ""
            lines.append(f"{name} & {s} & {fmt(h['w2_20'])} & {fmt(h['w2_150'])} & {fmt(h['c4_20'])} & {fmt(h['c4_150'])} \\\\")
    lines.append(r"\midrule")
    for k, s in enumerate((0, 1, 2)):
        h = H[f"J12s{s}"]
        lines.append(f"{'J12 ($s = 0.125$)' if k == 0 else ''} & {s} & {fmt(h['w2_20'])} & {fmt(h['w2_150'])} & "
                     f"{fmt(h['c4_20'])} & {fmt(h['c4_150'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_horizon.tex", "\n".join(lines) + "\n")


def figure_convergence(out, L):
    """pgfplots series: held-out WikiText-2 and best search fitness vs evaluated tokens."""
    series = {"E3": SEEDS["E3"], "IA": SEEDS["IA"], "DW": [0], "P4": [0, 1], "LX": [0]}
    style = {
        "E3": "thesisblue, thick", "IA": "thesisorange, thick", "DW": "thesisaqua, thick",
        "P4": "black!65, thick, densely dashed", "LX": "violet, thick, densely dotted",
    }
    legend = {"E3": "E3 (3 seeds)", "IA": "IA (3 seeds)", "DW": "DW (seed 0)", "P4": "P4 (2 seeds)", "LX": "LX (seed 0)"}
    w2_parts, fit_parts = [], []
    for code, seeds in series.items():
        logs = {s: generation_rows(f"{code}s{s}") for s in seeds}
        pts_w2, pts_fit = [], []
        for g in range(11, 150, 5):  # held-out diagnostics at generations 1, 6, 11, ...; start after 10 generations
            x = st.mean(tokens_before(logs[s], g) for s in seeds) / 1e6
            y = st.mean(float(logs[s][g - 1]["wikitext2_ppl"]) for s in seeds)
            pts_w2.append(f"({x:.2f},{y:.4f})")
        x_end = st.mean(L[f"{code}s{s}"]["tokens"] for s in seeds) / 1e6
        pts_w2.append(f"({x_end:.2f},{st.mean(L[f'{code}s{s}']['w2'] for s in seeds):.4f})")
        for g in range(5, 151, 5):
            x = st.mean(int(logs[s][g - 1]["evaluation_tokens_search_cumulative"]) for s in seeds) / 1e6
            y = st.mean(float(logs[s][g - 1]["best_search_fitness"]) for s in seeds)
            pts_fit.append(f"({x:.2f},{y:.4f})")
        w2_parts.append(f"\\addplot[{style[code]}, mark=none] coordinates {{{' '.join(pts_w2)}}};")
        fit_parts.append(f"\\addplot[{style[code]}, mark=none] coordinates {{{' '.join(pts_fit)}}};\n"
                         f"\\addlegendentry{{{legend[code]}}}")
    write(out, "fig_convergence_w2.tex", "\n".join(w2_parts) + "\n")
    write(out, "fig_convergence_fitness.tex", "\n".join(fit_parts) + "\n")


def operator_stats(label):
    rows = generation_rows(label)
    offspring, winners = Counter(), Counter()
    replaced = 0
    xo = Counter()
    for r in rows:
        summary = json.loads(r["mutation_summary"])
        for kind, n in summary.get("generated_offspring_by_type", {}).items():
            offspring[kind] += int(n)
        winners[r["selected_parent_mutation_type"]] += 1
        replaced += r["accepted_parent_replacement"] == "True"
        diag = summary.get("crossover_diagnostics") or {}
        for key in ("crossover_offspring_attempted", "crossover_duplicates", "crossover_no_legal_exchange",
                    "crossover_offspring", "crossover_infeasible_candidates"):
            xo[key] += int(diag.get(key) or 0)
    return {"gens": len(rows), "offspring": offspring, "winners": winners, "replaced": replaced, "xo": xo,
            "runtime_h": float(rows[-1]["runtime_seconds_cumulative"]) / 3600}


def table_operators(out):
    """Offspring by type, origin of the best candidate, and LX diagnostics."""
    kinds = ["depth", "quantization", "interaction_aware", "local exchange crossover"]
    lines = [
        r"\begin{tabular}{@{}lrrrrrrrrr@{}}", r"\toprule",
        r"& \multicolumn{4}{c}{Offspring per generation} & \multicolumn{5}{c}{Origin of the best candidate (generations)} \\",
        r"\cmidrule(lr){2-5}\cmidrule(l){6-10}",
        r"Run & S & Q & C & X & S & Q & C & X & kept \\",
        r"\midrule",
    ]
    for label in ("E3s0", "E3s1", "E3s2", "IAs0", "IAs1", "IAs2", "DWs0", "P4s0", "P4s1", "LXs0"):
        stats = operator_stats(label)
        n = stats["gens"]
        mix = [f"{stats['offspring'][k] / n:.0f}" if stats["offspring"][k] else "--" for k in kinds]
        w = stats["winners"]
        won = [str(w.get(k, 0)) if stats["offspring"][k] else "--" for k in kinds] + [str(w.get("parent", 0))]
        lines.append(f"{label[:-2]} s{label[-1]} & " + " & ".join(mix + won) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_operators.tex", "\n".join(lines) + "\n")
    lx = operator_stats("LXs0")["xo"]
    stats = {k: int(v) for k, v in lx.items()}
    (out / "lx_crossover_stats.json").write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    return stats


def table_cost(out, L):
    lines = [
        r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
        r"Variant & Seeds & Evaluations & Tokens & Search time (h) & h per $10^8$ tokens \\", r"\midrule",
    ]
    for code in ("E3", "IA", "DW", "P4", "LX"):
        seeds = SEEDS[code]
        hours = [operator_stats(f"{code}s{s}")["runtime_h"] for s in seeds]
        r = L[f"{code}s{seeds[0]}"]
        per = [h / (L[f"{code}s{s}"]["tokens"] / 1e8) for h, s in zip(hours, seeds)]
        hours_txt = ", ".join(f"{h:.1f}" + ("\\textsuperscript{a}" if f"{code}s{s}" in RESUMED else "")
                              for h, s in zip(hours, seeds))
        per_txt = f"{min(per):.1f}--{max(per):.1f}" if len(per) > 1 else f"{per[0]:.1f}"
        evals = f"{r['evals']:,}".replace(",", "{,}")
        lines.append(f"{code} & {len(seeds)} & {evals} & {r['tokens'] / 1e6:.1f}\\,M & {hours_txt} & {per_txt} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_cost.tex", "\n".join(lines) + "\n")


