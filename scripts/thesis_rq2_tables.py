LEDGER_CONDITION = {
    "E3": "E3_joint_s025_standard_g150", "IA": "joint_s025_ia_g150", "DW": "depthwarm_g150",
    "P4": "joint_s025_pop4_g150", "LX": "joint_s025_localxover_pop4_g150", "J12": "joint_s0125_g150",
}
VARIANT_LABEL = {
    "E3": "Standard (E3)", "IA": "Interaction-aware (IA)", "DW": "Warm start (DW)",
    "P4": "Population (P4)", "LX": "Crossover (LX)",
}
RESUMED = {"E3s1": "3 attempts", "P4s0": "resumed at $G = 18$"}
SEEDS = {"E3": [0, 1, 2], "IA": [0, 1, 2], "DW": [0], "P4": [0, 1], "LX": [0]}


def fmt(x, d=3):
    return f"{x:.{d}f}"


def ms(values, d=3):
    if len(values) == 1:
        return fmt(values[0], d)
    return f"{fmt(st.mean(values), d)} $\\pm$ {fmt(st.pstdev(values), d)}"


def signed(x, d=3):
    return ("$+$" if x >= 0 else "$-$") + fmt(abs(x), d)


def write(out: Path, name: str, text: str) -> None:
    out.mkdir(parents=True, exist_ok=True)
    header = "% Generated by evopress/scripts/thesis_rq2_tables.py. Do not edit by hand.\n"
    (out / name).write_text(header + text, encoding="utf-8")


def ledger() -> dict[str, dict[str, float]]:
    out = {}
    names = {v: k for k, v in LEDGER_CONDITION.items()}
    for row in csv.DictReader(LEDGER.open(encoding="utf-8")):
        if row["condition"] in names:
            out[f"{names[row['condition']]}s{row['seed']}"] = {
                "w2": float(row["wikitext2_ppl"]), "c4": float(row["c4_ppl"]),
                "kl": float(row["final_calibration_kl"]), "evals": int(row["candidate_evaluations"]),
                "tokens": int(row["search_tokens"]),
            }
    return out


def generation_rows(label: str) -> list[dict[str, str]]:
    by_gen: dict[int, dict[str, str]] = {}
    for rel in RUNS[label]:
        for row in csv.DictReader((RAW / rel / "generation_log.csv").open(encoding="utf-8")):
            by_gen[int(row["generation"])] = row  # later rows (attempts) win; removes duplicates
    gens = sorted(by_gen)
    if gens != list(range(1, gens[-1] + 1)):
        raise ValueError(f"{label}: generations are not contiguous")
    return [by_gen[g] for g in gens]


def tokens_before(rows, g: int) -> int:
    """Evaluated tokens after g - 1 generations (initial evaluation included)."""
    if g == 1:
        first = rows[0]
        per_gen = sum(int(first[f"evaluation_tokens_stage_{s}"]) for s in (1, 2, 3))
        return int(first["evaluation_tokens_search_cumulative"]) - per_gen
    return int(rows[g - 2]["evaluation_tokens_search_cumulative"])


