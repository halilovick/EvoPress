def smart(v, d=2):
    if v >= 1000:
        return f"{v:,.0f}".replace(",", "{,}")
    if v >= 100:
        return f"{v:.1f}"
    return f"{v:.{d}f}"


def fmt_range(values, d=2):
    if len(values) > 1 and max(values) > 3 * min(values):
        return " / ".join(smart(v, d) for v in values)
    if len(values) == 1:
        return smart(values[0], d)
    return ms(values, d)


def spread(values):
    return len(values) > 1 and max(values) > 3 * min(values)


def baseline_rows(label, ids, r):
    """One row with mean +- SD, or one row per mask if a metric differs by more than 3x."""
    w2, c4, kl = r(ids, "wikitext2_ppl"), r(ids, "c4_ppl"), r(ids, "calibration_kl")
    if spread(w2) or spread(c4) or spread(kl):
        base = label.replace("masks (3)", "mask")
        return [f"{base} {i + 1} & {smart(a)} & {smart(b)} & {smart(c, 3)} \\\\"
                for i, (a, b, c) in enumerate(zip(w2, c4, kl))]
    return [f"{label} & {fmt_range(w2)} & {fmt_range(c4)} & {fmt_range(kl, 3)} \\\\"]


