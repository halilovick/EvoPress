TYPES = ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"]


def table_bits_by_type(out):
    lines = [
        r"\begin{tabular}{@{}lrrrrrrrr@{}}", r"\toprule",
        r"Search & \texttt{q} & \texttt{k} & \texttt{v} & \texttt{o} & \texttt{gate} & \texttt{up} & \texttt{down} & All active \\",
        r"\midrule",
    ]
    for fam, label, s in (("E2", "Quantization-only (E2), $s = 0$", 0.0), ("J12", "Joint (J12), $s = 0.125$", 0.125),
                          ("E3", "Joint (E3), $s = 0.25$", 0.25)):
        per_type = {t: [] for t in TYPES}
        for i in SEEDS:
            cand = load_final_candidate(REPO_ROOT / FULLSPACE_CANDIDATES[f"{fam}s{i}"])
            for t in TYPES:
                vals = [b for n, b in cand["bits"].items() if n.endswith(t) and module_is_active(n, cand["drop"])]
                per_type[t].append(st.mean(vals))
        lines.append(label + " & " + " & ".join(num(st.mean(per_type[t])) for t in TYPES) + f" & {AVG_BITS[s]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_bits_by_type.tex", "\n".join(lines) + "\n")


def figure_removals(out):
    """TikZ grid: number of seeds (0-3) removing each sublayer, for J12 and E3."""
    cell, pitch, row_h = 0.30, 0.32, 0.42
    blocks = []
    tops = {"J12": 0.0, "E3": -1.35}
    for fam, top in tops.items():
        counts = {"attn": [0] * 32, "mlp": [0] * 32}
        for i in SEEDS:
            cand = load_final_candidate(REPO_ROOT / FULLSPACE_CANDIDATES[f"{fam}s{i}"])
            for kind in counts:
                for j in range(32):
                    counts[kind][j] += int(cand["drop"][kind][j])
        label = "$s = 0.125$ (J12)" if fam == "J12" else "$s = 0.25$ (E3)"
        blocks.append(f"\\node[anchor=south west, font=\\footnotesize, inner sep=1pt] at (0,{top + 0.04:.2f}) {{{label}}};")
        for r, kind in enumerate(("attn", "mlp")):
            y = top - r * row_h
            name = "attention" if kind == "attn" else "MLP"
            blocks.append(f"\\node[anchor=east, font=\\scriptsize] at (-0.05,{y - 0.19:.2f}) {{{name}}};")
            for j, c in enumerate(counts[kind]):
                shade = {0: "white", 1: "thesisblue!25", 2: "thesisblue!60", 3: "thesisblue"}[c]
                blocks.append(f"\\fill[{shade}] ({j * pitch:.2f},{y:.2f}) rectangle ++({cell},-0.38);")
            blocks.append(f"\\draw[gray!60] (0,{y:.2f}) rectangle ({32 * pitch - 0.02:.2f},{y - 0.38:.2f});")
    bottom = tops["E3"] - row_h - 0.38
    for j in (0, 4, 8, 12, 16, 20, 24, 28, 31):
        blocks.append(f"\\node[font=\\scriptsize, anchor=north] at ({j * pitch + cell / 2:.2f},{bottom - 0.02:.2f}) {{{j}}};")
    blocks.append(f"\\node[font=\\scriptsize, anchor=north] at ({16 * pitch:.2f},{bottom - 0.32:.2f}) {{decoder layer}};")
    legend_y = bottom - 0.85
    blocks.append(f"\\node[anchor=west, font=\\scriptsize] at (0,{legend_y - 0.15:.2f}) "
                  "{Number of seeds that remove the sublayer:};")
    x = 6.4
    for c, shade in ((0, "white"), (1, "thesisblue!25"), (2, "thesisblue!60"), (3, "thesisblue")):
        blocks.append(f"\\filldraw[fill={shade}, draw=gray!60] ({x:.2f},{legend_y:.2f}) rectangle ++(0.30,-0.30);")
        blocks.append(f"\\node[anchor=west, font=\\scriptsize] at ({x + 0.32:.2f},{legend_y - 0.15:.2f}) {{{c}}};")
        x += 1.0
    write(out, "fig_removals.tex", "\n".join(blocks) + "\n")


def table_screening(out):
    rows = list(csv.DictReader(open(SCREEN, encoding="utf-8")))
    by = {}
    for r in rows:
        by.setdefault(r["method"], []).append(float(r["wikitext2_ppl"]))
    spec = [
        ("depth_uniform", "Depth-only mask, uniform 3-bit \\texttt{q\\_proj}", "572"),
        ("independent", "Depth-only mask $+$ quantization-only profile", "$2 \\times 572$"),
        ("seq_depth_to_quant_frozen", "Structure $\\rightarrow$ quantization, frozen mask", "1{,}113"),
        ("seq_quant_to_depth_frozen", "Quantization $\\rightarrow$ structure, frozen bit-widths", "1{,}144"),
        ("joint_g20", "Joint search, $G = 20$", "572"),
        ("joint_g50", "Joint search, $G = 50$", "1{,}382"),
    ]
    lines = [r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{74mm}rl@{}}", r"\toprule",
             r"Method (screening protocol, $s = 0.25$) & Evaluations & WikiText-2 \\", r"\midrule"]
    for key, label, evals in spec:
        vals = by[key]
        lines.append(f"{label} & {evals} & {ms(vals, 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write(out, "tab_screening.tex", "\n".join(lines) + "\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    ledger, replay = load_inputs()
    table_reference(out, ledger, replay)
    table_main(out, ledger, replay)
    figure_sparsity(out, ledger, replay)
    table_decomposition(out, ledger, replay)
    table_baselines(out, ledger, replay)
    table_allocation_per_seed(out, replay)
    table_bits_by_type(out)
    figure_removals(out)
    table_screening(out)
    print(f"wrote {sorted(p.name for p in out.iterdir())}")


if __name__ == "__main__":
    main()
