def num(x, d=2):
    return f"{x:.{d}f}"


def ms(values, d=2):
    if len(values) == 1:
        return num(values[0], d)
    return f"{num(st.mean(values), d)} $\\pm$ {num(st.pstdev(values), d)}"


def thousands(n):
    return f"{n:,}".replace(",", "{,}")


def load_inputs():
    ledger = list(csv.DictReader(open(LEDGER, encoding="utf-8")))
    replay = {r["id"]: r for r in csv.DictReader(open(REPLAY, encoding="utf-8"))}
    return ledger, replay


def ledger_values(ledger, condition, key):
    return [float(r[key]) for r in ledger if r["condition"] == condition and r[key] not in ("", None)]


def replay_values(replay, ids, key):
    return [float(replay[i][key]) for i in ids]


def write(out: Path, name: str, text: str):
    (out / name).write_text(HEADER + text, encoding="utf-8")


